/** M2 client-side wx.login attempt boundary; never a Supabase session. */
export type LoginCodeResult = Readonly<{ code?: unknown }>;
export type LoginCodePort = Readonly<{ login(): Promise<LoginCodeResult> }>;
export type LoginAttempt = Readonly<{
  requestId: string;
  nonce: string;
  code: string;
}>;
export type LoginAttemptOutcome =
  | Readonly<{ status: "CODE_READY_FOR_TRUSTED_SERVER"; attempt: LoginAttempt }>
  | Readonly<{
      status: "LOGIN_BLOCKED";
      reason: "INVALID_INPUT" | "WX_LOGIN_FAILED" | "STALE_ATTEMPT";
    }>;

const safeId = /^[A-Za-z0-9_-]{16,128}$/;
const safeCode = /^[A-Za-z0-9_-]{4,1024}$/;

/** Identifiers must be generated by a cryptographically secure platform adapter.
 * Never use Math.random, Date.now, a nickname or a profile ID as a nonce.
 * Only the latest attempt may return a code; no code is persisted or logged.
 */
export class WechatLoginAttemptGate {
  private generation = 0;
  private readonly port: LoginCodePort;

  constructor(port: LoginCodePort) {
    this.port = port;
  }

  invalidate(): void {
    this.generation++;
  }

  async acquire(requestId: string, nonce: string): Promise<LoginAttemptOutcome> {
    const generation = ++this.generation;
    if (!safeId.test(requestId) || !safeId.test(nonce)) {
      return { status: "LOGIN_BLOCKED", reason: "INVALID_INPUT" };
    }

    let result: LoginCodeResult;
    try {
      result = await this.port.login();
    } catch {
      return { status: "LOGIN_BLOCKED", reason: "WX_LOGIN_FAILED" };
    }

    if (generation !== this.generation) {
      return { status: "LOGIN_BLOCKED", reason: "STALE_ATTEMPT" };
    }
    if (!result || typeof result.code !== "string" || !safeCode.test(result.code)) {
      return { status: "LOGIN_BLOCKED", reason: "WX_LOGIN_FAILED" };
    }
    return {
      status: "CODE_READY_FOR_TRUSTED_SERVER",
      attempt: { requestId, nonce, code: result.code },
    };
  }
}
